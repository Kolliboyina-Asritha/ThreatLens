def prepare_dataset():
    """Generates clean, deduplicated dataset with all 18 features extracted."""
    os.makedirs(os.path.dirname(RAW_DATA_PATH), exist_ok=True)
    os.makedirs(os.path.dirname(PROCESSED_DATA_PATH), exist_ok=True)
    
    # 1. Assemble raw URL list with ground-truth binary label: 0=benign, 1=malicious
    benign_rows = [{"url": u.strip(), "label": 0, "type": "benign"} for u in BENIGN_URLS_SAMPLES if u.strip()]
    malicious_rows = [{"url": u.strip(), "label": 1, "type": "malicious"} for u in MALICIOUS_URLS_SAMPLES if u.strip()]
    
    raw_df = pd.DataFrame(benign_rows + malicious_rows)
    
    # Deduplicate raw URLs
    initial_count = len(raw_df)
    raw_df = raw_df.drop_duplicates(subset=["url"]).reset_index(drop=True)
    raw_df.to_csv(RAW_DATA_PATH, index=False)
    
    print(f"[*] Raw Dataset assembled: {len(raw_df)} total URLs ({initial_count - len(raw_df)} duplicates removed)")
    print(f"    - Benign samples: {(raw_df['label'] == 0).sum()}")
    print(f"    - Malicious samples: {(raw_df['label'] == 1).sum()}")
    
    # 2. Extract deterministic 18-dimension feature vector for each URL
    feature_records = []
    for idx, row in raw_df.iterrows():
        url = row["url"]
        label = row["label"]
        feats = extract_features_from_url(url)
        feats["label"] = label
        feats["url"] = url
        feature_records.append(feats)
        
    features_df = pd.DataFrame(feature_records)
    
    # Verify no missing values
    assert features_df[FEATURE_NAMES].isnull().sum().sum() == 0, "Missing values found in feature extraction!"
    
    features_df.to_csv(PROCESSED_DATA_PATH, index=False)
    print(f"[+] Processed Features saved to: {PROCESSED_DATA_PATH}")
    print(f"    - Feature schema: {len(FEATURE_NAMES)} features across {len(features_df)} rows.")
    return features_df


